package ex_11_for_loops;

public class lab5_if_loop {
    static void main(String[] args) {
        for(int nishu=0;nishu<18;nishu++){
            if(nishu>16){
                System.out.println("gift from god" );
            }
            else{
                System.out.println("no gift");
            }
        }
    }
}
