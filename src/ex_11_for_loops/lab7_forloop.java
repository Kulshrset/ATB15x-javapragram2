package ex_11_for_loops;

public class lab7_forloop {
    static void main(String[] args) {
       for(int i=0;i<=9;i++) {
           System.out.println(i);
       }

        for(int i=0;i<=9;++i) {
            System.out.println(i);
        }

        for(int i=0;i<9;i++) {
            System.out.println(i);
        }
    }

}
