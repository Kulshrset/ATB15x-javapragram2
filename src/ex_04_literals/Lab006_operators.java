package ex_04_literals;

public class Lab006_operators {
    static void main(String[] args) {
        int a=90;
        int b=8;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        float c=3.0f;
        System.out.println(a/c);
        System.out.println("a+b");


    }

}
