package ex_09_inc_dec;

public class lab03_pre {

    static void main(String[] args) {
        int a=0;
        int b=10;
        int c=10;


        System.out.println(a++ + a);
        System.out.println(a++);
        System.out.println(b++ + ++b);
        System.out.println(b);
        System.out.println(b++);
        System.out.println(++b);
        System.out.println(++c);
    }
}
